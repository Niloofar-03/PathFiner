#!/usr/bin/env python3
"""Rebuild screens.js from the design files in design/.

Run this after replacing any file in design/ with a newer export:
    python3 build.py
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent
DESIGN = ROOT / "design"

canvas = json.loads((DESIGN / "canvas.json").read_text(encoding="utf-8"))
order = [f for f in canvas["order"] if (DESIGN / f).exists()]

screens = {}
for fname in order:
    text = (DESIGN / fname).read_text(encoding="utf-8")
    name = fname[: -len(".dc.html")]
    xdc = re.search(r"<x-dc>(.*)</x-dc>", text, re.S)
    if not xdc:
        raise SystemExit(f"{fname}: no <x-dc> block found")
    body = xdc.group(1)
    helmet = re.search(r"<helmet>(.*?)</helmet>", body, re.S)
    template = re.sub(r"<helmet>.*?</helmet>", "", body, count=1, flags=re.S)
    script = re.search(r'<script type="text/x-dc"[^>]*>(.*?)</script>', text, re.S)
    if not script:
        raise SystemExit(f"{fname}: no data-dc-script block found")
    screens[name] = {
        "title": canvas["boards"].get(fname, {}).get("title", name),
        "template": template.strip(),
        "helmet": helmet.group(1).strip() if helmet else "",
        "script": script.group(1).strip(),
    }

out = (
    "/* Generated by build.py from design/ - do not edit by hand. */\n"
    "window.PF_SCREENS = " + json.dumps(screens, ensure_ascii=False, indent=1) + ";\n"
    "window.PF_ORDER = " + json.dumps(list(screens.keys())) + ";\n"
    'window.PF_START = "Splash";\n'
)
(ROOT / "screens.js").write_text(out, encoding="utf-8")
print(f"Wrote screens.js with {len(screens)} screens: {', '.join(screens)}")
